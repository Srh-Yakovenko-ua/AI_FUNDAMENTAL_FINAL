"""Робота з текстом: стемінг і міра схожості.

Чисті функції без стану: на однакових входах завжди дають однаковий результат,
тому їх можна тестувати ізольовано, без бази й без мережі.
"""

STOP_WORDS = {
    "формула", "формулу", "формули", "яка", "який", "яке", "що", "таке", "як",
    "мені", "потрібна", "потрібно", "розкажи", "поясни", "для", "про", "будь",
    "ласка", "підкажи", "напиши", "покажи", "треба", "хочу", "знайти",
}

# Типові українські закінчення, від найдовших до найкоротших.
ENDINGS = ("ами", "ями", "ові", "ого", "ому", "ої", "ий", "ій", "ою", "ею",
           "ем", "ом", "ів", "ах", "ях", "і", "и", "е", "у", "ю", "а", "я", "о")

MIN_WORD_LENGTH = 3
STEM_LENGTH = 5
BETA_SQUARED = 4          # F2: повнота покриття запиту важить більше за точність


def stem_word(word: str) -> str:
    """Корінь слова, стійкий до українських відмінків.

    Обрізання до фіксованої довжини тут не працює. «закон» має пʼять літер
    і різалося до «зако», а «закону» шість і різалося до «закон»: найприродніший
    запит «формула закону Ома» не знаходив закон Ома. Тому спершу знімаємо
    закінчення, і лише потім обмежуємо довжину.
    """
    for ending in ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[:len(word) - len(ending)][:STEM_LENGTH]
    return word[:STEM_LENGTH]


def stems(text: str, drop_stop: bool = False) -> set:
    """Множина коренів значущих слів тексту."""
    words = [w.strip(".,;:!?()«»\"'") for w in text.lower().split()]
    return {
        stem_word(w) for w in words
        if len(w) >= MIN_WORD_LENGTH and not (drop_stop and w in STOP_WORDS)
    }


def lexical_score(query: str, target: str) -> float:
    """Двостороння міра схожості F2 між запитом і назвою.

    Чому саме двостороння, а не проста частка збігів. Назва «швидкість»
    складається з одного слова, тому запит «швидкість світла» покриває її
    на всі сто відсотків, і симетрична міра вважала б це відмінним збігом,
    хоча про світло в базі немає нічого. Слово запиту, якого немає в назві,
    це сигнал «питають не про це», і він має важити сильніше.
    """
    q, t = stems(query, drop_stop=True), stems(target)
    if not q or not t:
        return 0.0
    hits = len(q & t)
    if not hits:
        return 0.0
    precision, recall = hits / len(t), hits / len(q)
    return ((1 + BETA_SQUARED) * precision * recall
            / (BETA_SQUARED * precision + recall))


def format_number(value: float) -> str:
    """Число для школяра, а не для інженера.

    Три випадки, кожен закриває реальну помилку попередньої версії: великі
    числа не мають зриватися в експоненту (506 625, а не 5.066e+05), малі теж,
    а значущі цифри не можна втрачати (0 °C це 273.15 K, а не 273.1).
    """
    if value == int(value):
        return f"{int(value):,}".replace(",", " ")
    if abs(value) >= 10_000:
        return f"{value:,.2f}".rstrip("0").rstrip(".").replace(",", " ")
    if abs(value) >= 0.001:
        return f"{value:.6g}"
    return f"{value:.12f}".rstrip("0").rstrip(".") or "0"
